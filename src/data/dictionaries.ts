import type { FsrsCard, YouGlishClip } from '../core/fsrs/fsrsEngine';
import { EXPANDED_FSRS_CARDS } from './expandedCards';

const NOW = Date.now();
const DAY = 86_400_000;

interface CardSeed {
  id: string;
  word: string;
  ipa: string;
  pos: string;
  meaningVi: string;
  meaningEn: string;
  clozeSentence: string;
  translationVi: string;
  wordFamily: string[];
  collocations: string[];
  nuance: string;
  mnemonic: string;
  deck: string;
  cefr: 'A1' | 'A2' | 'B1' | 'B2' | 'C1' | 'C2';
  sourceTitle: string;
  rootId?: string;
  state?: 'new' | 'review';
  stability?: number;
  difficulty?: number;
  reps?: number;
  dueOffsetDays?: number;
  youglishContexts?: YouGlishClip[];
}

function buildCard(seed: CardSeed): FsrsCard {
  const isNew = (seed.state ?? 'new') === 'new';
  const offsetDays = seed.dueOffsetDays ?? 0;
  return {
    id: seed.id,
    word: seed.word,
    ipa: seed.ipa,
    pos: seed.pos,
    meaningVi: seed.meaningVi,
    meaningEn: seed.meaningEn,
    clozeSentence: seed.clozeSentence,
    clozeAnswer: seed.word,
    translationVi: seed.translationVi,
    wordFamily: seed.wordFamily,
    collocations: seed.collocations,
    nuance: seed.nuance,
    mnemonic: seed.mnemonic,
    deck: seed.deck,
    cefr: seed.cefr,
    sourceTitle: seed.sourceTitle,
    rootId: seed.rootId,
    youglishContexts: seed.youglishContexts ?? [
      {
        accent: 'US',
        speaker: 'TED Tech Talk',
        timestamp: '02:14',
        sentence: seed.clozeSentence.replace(/\{\{|\}\}/g, ''),
      },
      {
        accent: 'UK',
        speaker: 'BBC Business Daily',
        timestamp: '05:41',
        sentence: `In modern teams, "${seed.word}" captures an essential nuance in clear communication.`,
      },
      {
        accent: 'AUS',
        speaker: 'Sydney Founders Podcast',
        timestamp: '11:08',
        sentence: `We noticed how naturally "${seed.word}" fits into high-level technical discussions.`,
      },
    ],
    state: isNew ? 'new' : 'review',
    stability: seed.stability ?? 0,
    difficulty: seed.difficulty ?? 0,
    elapsedDays: isNew ? 0 : 4,
    scheduledDays: isNew ? 0 : Math.round(seed.stability ?? 4),
    reps: seed.reps ?? 0,
    lapses: 0,
    lastReview: isNew ? null : NOW - 4 * DAY,
    due: NOW + offsetDays * DAY - 5000,
  };
}

